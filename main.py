"""
UTC-PD 30μm Simulation
======================
V_bias = -7V | Rs = 5Ω (fixed) | Cj = 133.53fF (C-V -7V, fixed)

Circuit topology:
  I_ph ↑ ‖ Cj‖Rp ─── Rs ─── R_cpw+jωL_cpw ─── Node B ─── R_L
                                                      │
                                                   Cp_cpw

  H_ckt = V_B / I_ph = 1 / [(1 + Y_B·(Z_RL+Rs)) / Z_par + Y_B]
  Y_B   = jω·Cp_cpw + 1/R_eff,   R_eff = R_L ‖ Rp
  P_RL  = |I_ph · H_ph · H_ckt|² / (2·R_L)

CPW π-model: fixed at Open-device ADS Momentum values
  Cp_cpw = 28.93 fF, L_cpw = 218.9 pH
  R_cpw(f) = 0.764 + 0.1869·√(f/GHz)  Ω
"""

import numpy as np
