# ═══════════════════════════════════════════════════════════════════════
# 1. CPW π-MODEL  (fixed at Open-device ADS Momentum values)
# ═══════════════════════════════════════════════════════════════════════
Cp_cpw = 28.93e-15   # F
L_cpw  = 218.9e-12   # H
R0_cpw = 0.764       # Ω
al_cpw = 0.1869      # Ω/√GHz

def R_cpw(w):
    return R0_cpw + al_cpw * np.sqrt(np.maximum(w / (2*np.pi*1e9), 0))

# ═══════════════════════════════════════════════════════════════════════
# 2. DEVICE PARAMETERS  (fixed)
# ═══════════════════════════════════════════════════════════════════════
Rs_all   = 5.0
Cj_fixed = 133.53e-15
R_L      = 50.0
I_ph     = 1.0 * (30/40)**2 * 1e-3

# ═══════════════════════════════════════════════════════════════════════
# 3. TRANSIT TIMES & H_ph(ω)
# ═══════════════════════════════════════════════════════════════════════
v_os_InP    = 2.3e7 * 1e-2
v_os_InGaAs = 2.1e7 * 1e-2

W_A_undep = 480e-9
W_A_dep   = 160e-9
W_cliff   =  50e-9
W_C       = 740e-9
W_tot     = W_A_undep + W_A_dep + W_cliff + W_C

tau_A  = 7.862e-12
tau_Ad = W_A_dep / v_os_InGaAs
tau_cl = W_cliff  / v_os_InP
tau_C  = W_C      / v_os_InP

def H_ph(w):
    sinc = lambda x: np.sinc(x / np.pi)
    HA   = 1 / (1 + 1j*w*tau_A)
    HAd  = sinc(w*tau_Ad/2) * np.exp(-1j*(w*tau_A + w*tau_Ad/2))
    Hcl  = sinc(w*tau_cl/2) * np.exp(-1j*(w*tau_A + w*tau_Ad + w*tau_cl/2))
    Hco  = sinc(w*tau_C/2)  * np.exp(-1j*(w*tau_A + w*tau_Ad + w*tau_cl + w*tau_C/2))
    return (W_A_undep*HA + W_A_dep*HAd + W_cliff*Hcl + W_C*Hco) / W_tot

# ═══════════════════════════════════════════════════════════════════════
# 4. CIRCUIT FUNCTIONS
# ═══════════════════════════════════════════════════════════════════════
def R_eff(Rp):
    return R_L if np.isinf(Rp) else R_L * Rp / (R_L + Rp)

def Z_par(w, Cj, Rp):
    Z_Cj = 1 / (1j*w*Cj)
    return Z_Cj if np.isinf(Rp) else Z_Cj*Rp / (Z_Cj + Rp)

def H_ckt(w, Rs, Cj, Rp):
    Zp   = Z_par(w, Cj, Rp)
    Z_RL = R_cpw(w) + 1j*w*L_cpw
    Y_B  = 1j*w*Cp_cpw + 1/R_eff(Rp)
    return 1 / ((1 + Y_B*(Z_RL + Rs))/Zp + Y_B)

def sim_S11(w, Rs, Cj, Rp):
    Z_dev = Rs + Z_par(w, Cj, Rp)
    Zin   = 1 / (1j*w*Cp_cpw + 1/(R_cpw(w) + 1j*w*L_cpw + Z_dev))
    return (Zin - 50) / (Zin + 50)

def P_RL_dBm(I_ph_A, w, Rs, Cj, Rp):
    Ht  = H_ph(w) * H_ckt(w, Rs, Cj, Rp)
    P_W = I_ph_A**2 * np.abs(Ht)**2 / (2*R_L)
    return 10*np.log10(np.maximum(P_W, 1e-30) / 1e-3)

def get_bw(f, w, Rs, Cj, Rp):
    Ht = H_ph(w) * H_ckt(w, Rs, Cj, Rp)
    Hd = 20*np.log10(np.abs(Ht) / np.abs(Ht[0]))
    idx = np.where(Hd <= -3)[0]
    return f'{f[idx[0]]/1e9:.1f}' if len(idx) else '>50'

# ═══════════════════════════════════════════════════════════════════════
# 4b. 1 dB COMPRESSION PHOTOCURRENT  (I_max)
# ═══════════════════════════════════════════════════════════════════════
q_e       = 1.602e-19               # C
eps_0_si  = 8.854e-12               # F/m
eps_r_InP = 12.5
eps_InP   = eps_r_InP * eps_0_si    # F/m

v_os_InP_sat = 4e7 * 1e-2           # m/s  InP overshoot velocity (for I_max)
E_crit_InP   = 5e3 * 1e2            # V/m  critical field (5 kV/cm)

N_cliff_cm3 = 1.9e17                # cm⁻³
N_DC_cm3    = (1.5e16 + 1.2e16) / 2 # cm⁻³  averaged
N_DC_m3     = N_DC_cm3 * 1e6        # m⁻³

W_grade   = (15 + 15) * 1e-9        # m  grading layers
W_C_eff   = W_cliff + W_C           # m  effective collector = 790 nm

A_dev     = np.pi * (15e-6)**2       # m²  (30 µm diameter)
V_bi      = 0.9                      # V
m_mod     = 1.0                      # modulation index

dV_cliff  = q_e * N_cliff_cm3*1e6 * W_cliff**2 / (2*eps_InP)   # V

# K  [A/V]
K_sat = (2 * eps_InP * v_os_InP_sat / W_C_eff**2) * A_dev

# C_fix  [V]
C_fix = V_bi + dV_cliff - E_crit_InP * W_C_eff + q_e * N_DC_m3 * W_C**2 / (2*eps_InP)

def I_max_compression(w, Rs, Cj, Rp):
    """1 dB compression photocurrent I_max(ω) [A]."""
    Re  = R_eff(Rp)
    Z_ext = Rs + Re
    alpha = Z_ext * (1 + m_mod / np.sqrt(1 + (w * Cj * Z_ext)**2))
    return K_sat * (np.abs(-7.0) + C_fix) / (1 + K_sat * alpha / (1 + m_mod))

