def parse_s1p(data, f_max):
    mask = data[:, 0] <= f_max
    fr = data[mask, 0]
    S11 = 10**(data[mask, 1]/20) * np.exp(1j*np.deg2rad(data[mask, 2]))
    return fr, S11


def parse_freq_response(data_arr):
    f_ghz    = data_arr[:, 0]
    raw      = data_arr[:, 1]
    new_loss = np.interp(f_ghz, ref_f_GHz, ref_loss_dB)
    cal_pow  = raw + new_loss
    return f_ghz * 1e9, cal_pow - cal_pow[0]

